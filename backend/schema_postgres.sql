-- PostgreSQL schema for the public hosted demo (Neon or another PostgreSQL provider).
-- Run once in the empty hosted database, before the first app registration.

CREATE TABLE APP_ACCOUNT (
    ACCOUNT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    ROLE VARCHAR(10) NOT NULL DEFAULT 'USER' CHECK (ROLE IN ('ADMIN', 'USER')),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE GITHUB_USER (
    USER_ID BIGINT PRIMARY KEY,
    USERNAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(255),
    NAME VARCHAR(255),
    USER_TYPE VARCHAR(30),
    PROFILE_URL VARCHAR(500),
    LOCATION VARCHAR(255),
    CREATED_AT TIMESTAMPTZ
);

CREATE TABLE REPOSITORY (
    REPOSITORY_ID BIGINT PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    FULL_NAME VARCHAR(500),
    DESCRIPTION VARCHAR(4000),
    STARS BIGINT NOT NULL DEFAULT 0,
    FORKS BIGINT NOT NULL DEFAULT 0,
    OPEN_ISSUES BIGINT NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMPTZ,
    UPDATED_AT TIMESTAMPTZ,
    OWNER_ID BIGINT NOT NULL REFERENCES GITHUB_USER(USER_ID)
);

CREATE TABLE LANGUAGE (
    LANGUAGE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    LANGUAGE_NAME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE CONTRIBUTES_TO (
    USER_ID BIGINT NOT NULL REFERENCES GITHUB_USER(USER_ID),
    REPOSITORY_ID BIGINT NOT NULL REFERENCES REPOSITORY(REPOSITORY_ID) ON DELETE CASCADE,
    CONTRIBUTIONS BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (USER_ID, REPOSITORY_ID)
);

CREATE TABLE GIT_COMMIT (
    COMMIT_ID VARCHAR(40) PRIMARY KEY,
    COMMIT_MESSAGE VARCHAR(4000),
    COMMIT_DATE TIMESTAMPTZ,
    AUTHOR_ID BIGINT NOT NULL REFERENCES GITHUB_USER(USER_ID),
    REPOSITORY_ID BIGINT NOT NULL REFERENCES REPOSITORY(REPOSITORY_ID) ON DELETE CASCADE
);

CREATE TABLE ISSUE (
    ISSUE_ID BIGINT PRIMARY KEY,
    TITLE VARCHAR(500) NOT NULL,
    STATE VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL,
    CLOSED_AT TIMESTAMPTZ,
    CREATOR_ID BIGINT NOT NULL REFERENCES GITHUB_USER(USER_ID),
    REPOSITORY_ID BIGINT NOT NULL REFERENCES REPOSITORY(REPOSITORY_ID) ON DELETE CASCADE
);

CREATE TABLE PULL_REQUEST (
    PR_ID BIGINT PRIMARY KEY,
    TITLE VARCHAR(500) NOT NULL,
    STATE VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL,
    MERGED_AT TIMESTAMPTZ,
    CREATOR_ID BIGINT NOT NULL REFERENCES GITHUB_USER(USER_ID),
    REPOSITORY_ID BIGINT NOT NULL REFERENCES REPOSITORY(REPOSITORY_ID) ON DELETE CASCADE
);

CREATE TABLE APP_PASSWORD_RESET (
    TOKEN_HASH VARCHAR(64) PRIMARY KEY,
    ACCOUNT_ID BIGINT NOT NULL REFERENCES APP_ACCOUNT(ACCOUNT_ID) ON DELETE CASCADE,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    EXPIRES_AT TIMESTAMPTZ NOT NULL
);
CREATE INDEX IX_PASSWORD_RESET_ACCOUNT ON APP_PASSWORD_RESET(ACCOUNT_ID);

CREATE TABLE REPOSITORY_AUDIT (
    AUDIT_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    REPOSITORY_ID BIGINT NOT NULL,
    ACTION_TYPE VARCHAR(20) NOT NULL,
    ACTION_DATE TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION audit_repository_insert() RETURNS trigger AS $$
BEGIN
    INSERT INTO REPOSITORY_AUDIT (REPOSITORY_ID, ACTION_TYPE, ACTION_DATE)
    VALUES (NEW.REPOSITORY_ID, 'INSERT', CURRENT_TIMESTAMP);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_REPOSITORY_AUDIT
AFTER INSERT ON REPOSITORY
FOR EACH ROW EXECUTE FUNCTION audit_repository_insert();


