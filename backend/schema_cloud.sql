-- Fresh schema for Oracle Autonomous Database.
-- Run as a dedicated application schema user, not as ADMIN or SYSTEM.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE APP_ACCOUNT (
    ACCOUNT_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    USERNAME VARCHAR2(50) NOT NULL,
    EMAIL VARCHAR2(255) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(10) DEFAULT 'USER' NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UQ_APP_ACCOUNT_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_APP_ACCOUNT_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_APP_ACCOUNT_ROLE CHECK (ROLE IN ('ADMIN', 'USER'))
);

CREATE TABLE GITHUB_USER (
    USER_ID NUMBER(19,0) NOT NULL,
    USERNAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(255),
    NAME VARCHAR2(255),
    USER_TYPE VARCHAR2(30),
    PROFILE_URL VARCHAR2(500),
    LOCATION VARCHAR2(255),
    CREATED_AT TIMESTAMP(6),
    CONSTRAINT PK_GITHUB_USER PRIMARY KEY (USER_ID)
);

CREATE TABLE REPOSITORY (
    REPOSITORY_ID NUMBER(19,0) NOT NULL,
    NAME VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(500),
    DESCRIPTION VARCHAR2(4000),
    STARS NUMBER(10,0) DEFAULT 0,
    FORKS NUMBER(10,0) DEFAULT 0,
    OPEN_ISSUES NUMBER(10,0) DEFAULT 0,
    CREATED_AT TIMESTAMP(6),
    UPDATED_AT TIMESTAMP(6),
    OWNER_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_REPOSITORY PRIMARY KEY (REPOSITORY_ID),
    CONSTRAINT FK_REPO_OWNER FOREIGN KEY (OWNER_ID) REFERENCES GITHUB_USER (USER_ID)
);

CREATE TABLE LANGUAGE (
    LANGUAGE_ID NUMBER(10,0) NOT NULL,
    LANGUAGE_NAME VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_LANGUAGE PRIMARY KEY (LANGUAGE_ID)
);

CREATE TABLE CONTRIBUTES_TO (
    USER_ID NUMBER(19,0) NOT NULL,
    REPOSITORY_ID NUMBER(19,0) NOT NULL,
    CONTRIBUTIONS NUMBER(10,0) DEFAULT 0,
    CONSTRAINT PK_CONTRIBUTES PRIMARY KEY (USER_ID, REPOSITORY_ID),
    CONSTRAINT FK_CONTRIB_USER FOREIGN KEY (USER_ID) REFERENCES GITHUB_USER (USER_ID),
    CONSTRAINT FK_CONTRIB_REPO FOREIGN KEY (REPOSITORY_ID) REFERENCES REPOSITORY (REPOSITORY_ID)
);

CREATE TABLE GIT_COMMIT (
    COMMIT_ID VARCHAR2(40) NOT NULL,
    COMMIT_MESSAGE VARCHAR2(4000),
    COMMIT_DATE TIMESTAMP(6),
    AUTHOR_ID NUMBER(19,0) NOT NULL,
    REPOSITORY_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_GIT_COMMIT PRIMARY KEY (COMMIT_ID),
    CONSTRAINT FK_COMMIT_AUTHOR FOREIGN KEY (AUTHOR_ID) REFERENCES GITHUB_USER (USER_ID),
    CONSTRAINT FK_COMMIT_REPO FOREIGN KEY (REPOSITORY_ID) REFERENCES REPOSITORY (REPOSITORY_ID)
);

CREATE TABLE ISSUE (
    ISSUE_ID NUMBER(19,0) NOT NULL,
    TITLE VARCHAR2(500) NOT NULL,
    STATE VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    CLOSED_AT TIMESTAMP(6),
    CREATOR_ID NUMBER(19,0) NOT NULL,
    REPOSITORY_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_ISSUE PRIMARY KEY (ISSUE_ID),
    CONSTRAINT FK_ISSUE_CREATOR FOREIGN KEY (CREATOR_ID) REFERENCES GITHUB_USER (USER_ID),
    CONSTRAINT FK_ISSUE_REPO FOREIGN KEY (REPOSITORY_ID) REFERENCES REPOSITORY (REPOSITORY_ID)
);

CREATE TABLE PULL_REQUEST (
    PR_ID NUMBER(19,0) NOT NULL,
    TITLE VARCHAR2(500) NOT NULL,
    STATE VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    MERGED_AT TIMESTAMP(6),
    CREATOR_ID NUMBER(19,0) NOT NULL,
    REPOSITORY_ID NUMBER(19,0) NOT NULL,
    CONSTRAINT PK_PR PRIMARY KEY (PR_ID),
    CONSTRAINT FK_PR_CREATOR FOREIGN KEY (CREATOR_ID) REFERENCES GITHUB_USER (USER_ID),
    CONSTRAINT FK_PR_REPO FOREIGN KEY (REPOSITORY_ID) REFERENCES REPOSITORY (REPOSITORY_ID)
);

CREATE TABLE APP_PASSWORD_RESET (
    TOKEN_HASH VARCHAR2(64) NOT NULL,
    ACCOUNT_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_APP_PASSWORD_RESET PRIMARY KEY (TOKEN_HASH),
    CONSTRAINT FK_PASSWORD_RESET_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES APP_ACCOUNT (ACCOUNT_ID) ON DELETE CASCADE
);
CREATE INDEX IX_PASSWORD_RESET_ACCOUNT ON APP_PASSWORD_RESET (ACCOUNT_ID);

CREATE TABLE REPOSITORY_AUDIT (
    AUDIT_ID NUMBER NOT NULL,
    REPOSITORY_ID NUMBER NOT NULL,
    ACTION_TYPE VARCHAR2(20) NOT NULL,
    ACTION_DATE TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REPOSITORY_AUDIT PRIMARY KEY (AUDIT_ID)
);
CREATE SEQUENCE REPOSITORY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_REPOSITORY_AUDIT
AFTER INSERT ON REPOSITORY
FOR EACH ROW
BEGIN
    INSERT INTO REPOSITORY_AUDIT (AUDIT_ID, REPOSITORY_ID, ACTION_TYPE, ACTION_DATE)
    VALUES (REPOSITORY_SEQ.NEXTVAL, :NEW.REPOSITORY_ID, 'INSERT', SYSTIMESTAMP);
END;
