-- One-use, expiring email password-reset tokens. Only token hashes are stored.
CREATE TABLE "SYSTEM"."APP_PASSWORD_RESET"
(
    "TOKEN_HASH" VARCHAR2(64) NOT NULL,
    "ACCOUNT_ID" NUMBER NOT NULL,
    "CREATED_AT" TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    "EXPIRES_AT" TIMESTAMP(6) NOT NULL,
    CONSTRAINT "PK_APP_PASSWORD_RESET" PRIMARY KEY ("TOKEN_HASH"),
    CONSTRAINT "FK_PASSWORD_RESET_ACCOUNT" FOREIGN KEY ("ACCOUNT_ID")
        REFERENCES "SYSTEM"."APP_ACCOUNT" ("ACCOUNT_ID") ON DELETE CASCADE
);
CREATE INDEX "SYSTEM"."IX_PASSWORD_RESET_ACCOUNT"
    ON "SYSTEM"."APP_PASSWORD_RESET" ("ACCOUNT_ID");
-- Repository insert audit objects used by TRG_REPOSITORY_AUDIT.
CREATE SEQUENCE "SYSTEM"."REPOSITORY_SEQ"
    START WITH 1 INCREMENT BY 1 NOCACHE;


CREATE TABLE "SYSTEM"."REPOSITORY_AUDIT"
(
    "AUDIT_ID" NUMBER NOT NULL,
    "REPOSITORY_ID" NUMBER NOT NULL,
    "ACTION_TYPE" VARCHAR2(20) NOT NULL,
    "ACTION_DATE" TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT "PK_REPOSITORY_AUDIT" PRIMARY KEY ("AUDIT_ID")
);

CREATE OR REPLACE TRIGGER "SYSTEM"."TRG_REPOSITORY_AUDIT"
AFTER INSERT ON "SYSTEM"."REPOSITORY"
FOR EACH ROW
BEGIN
    INSERT INTO "SYSTEM"."REPOSITORY_AUDIT"
        ("AUDIT_ID", "REPOSITORY_ID", "ACTION_TYPE", "ACTION_DATE")
    VALUES
        ("SYSTEM"."REPOSITORY_SEQ".NEXTVAL, :NEW."REPOSITORY_ID", 'INSERT', SYSTIMESTAMP);
END;
