-- Run once as the owner of APP_ACCOUNT before enabling email password recovery.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE APP_PASSWORD_RESET (
    TOKEN_HASH VARCHAR2(64) NOT NULL,
    ACCOUNT_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_APP_PASSWORD_RESET PRIMARY KEY (TOKEN_HASH),
    CONSTRAINT FK_PASSWORD_RESET_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES APP_ACCOUNT (ACCOUNT_ID) ON DELETE CASCADE
);

CREATE INDEX IX_PASSWORD_RESET_ACCOUNT ON APP_PASSWORD_RESET (ACCOUNT_ID);
