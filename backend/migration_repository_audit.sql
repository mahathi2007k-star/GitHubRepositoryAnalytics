-- One-time repair for the repository audit trigger in an existing SYSTEM schema.
-- Run as SYSTEM (or SYS with explicit SYSTEM object names).
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE SYSTEM.REPOSITORY_AUDIT (
    AUDIT_ID NUMBER NOT NULL,
    REPOSITORY_ID NUMBER NOT NULL,
    ACTION_TYPE VARCHAR2(20) NOT NULL,
    ACTION_DATE TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REPOSITORY_AUDIT PRIMARY KEY (AUDIT_ID)
);

CREATE SEQUENCE SYSTEM.REPOSITORY_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE;

ALTER TRIGGER SYSTEM.TRG_REPOSITORY_AUDIT COMPILE;
SHOW ERRORS TRIGGER SYSTEM.TRG_REPOSITORY_AUDIT

SELECT OWNER, TRIGGER_NAME, STATUS
FROM DBA_TRIGGERS
WHERE OWNER = 'SYSTEM' AND TRIGGER_NAME = 'TRG_REPOSITORY_AUDIT';
